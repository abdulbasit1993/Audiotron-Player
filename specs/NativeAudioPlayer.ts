import type { TurboModule } from 'react-native';
import { TurboModuleRegistry } from 'react-native';

export interface PlaybackStateEvent {
  position: number;
  duration: number;
  state: 'playing' | 'paused' | 'stopped' | 'completed' | 'error';
  bufferedPosition?: number;
  error?: string;
}

export interface Spec extends TurboModule {
  load(uri: string): Promise<void>;
  play(): Promise<void>;
  pause(): Promise<void>;
  stop(): Promise<void>;

  getDuration(): Promise<number>;
  getCurrentPosition(): Promise<number>;
  seekTo(positionMs: number): Promise<void>;

  setLoopA(): Promise<number>;
  setLoopB(): Promise<number>;
  clearLoop(): Promise<void>;
  release(): Promise<void>;

  // NEW: Event emitter methods (auto-generated by codegen when present)
  addListener(eventName: string): void;
  removeListeners(count: number): void;
}

export default TurboModuleRegistry.getEnforcing<Spec>('NativeAudioPlayer');
